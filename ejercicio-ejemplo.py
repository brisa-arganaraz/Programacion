def sumar(numero_a: int, numero_b: int) -> int:
    """ Funcion que se encarga de sumar dos números enteros
    Args:
        numero_a (int): Primer número
        numero_b (int): Segundo Número
    Returns:
        int: Devuelve la suma entre estos dos números """
    suma = numero_a + numero_b
    return suma

resultado = sumar(5, 3)
print(resultado)  

def resta(numero_a: int, numero_b: int) -> int:
    """ Funcion que se encarga de restar dos números enteros
    Args:
        numero_a (int): Primer número
        numero_b (int): Segundo Número
    Returns:
        int: Devuelve la resta entre estos dos números """
    resta = numero_a - numero_b
    return resta

resultado = resta(5, 3)
print(resultado)  

def multiplicacion(numero_a: int, numero_b: int) -> int:
    """ Funcion que se encarga de la multiplicacion dos números enteros
    Args:
        numero_a (int): Primer número
        numero_b (int): Segundo Número
    Returns:
        int: Devuelve la multiplicacion entre estos dos números """
    multiplicacion = numero_a - numero_b
    return multiplicacion

resultado = multiplicacion(5, 3)
print(resultado)  

def division(numero_a: int, numero_b: int) -> int:
    """ Funcion que se encarga de la division dos números enteros
    Args:
        numero_a (int): Primer número
        numero_b (int): Segundo Número
    Returns:
        int: Devuelve la division entre estos dos números """
    division = numero_a / numero_b
    return division

resultado = division(5, 3)
print(resultado)  
